// 六亲：以宫五行为「我」，爻支五行相对定亲
const WX_ORDER = ['木', '火', '土', '金', '水'];
export function liuqin(gongWx: string, zhiWx: string): string {
  if (zhiWx === gongWx) return '兄弟';
  const gi = WX_ORDER.indexOf(gongWx), zi = WX_ORDER.indexOf(zhiWx);
  const rel = ((zi - gi) % 5 + 5) % 5;
  // rel: 1=我生→子孙 2=我克→妻财 3=克我→官鬼 4=生我→父母
  return rel === 1 ? '子孙' : rel === 2 ? '妻财' : rel === 3 ? '官鬼' : rel === 4 ? '父母' : '兄弟';
}
